"""Solumia's own apps for each device: phone/tablet, watch, PC and laptop.

Source: GitHub Releases of `names.REPOSITORY`. File names per release (generated by CI):
`solumia-X.Y.Z-android.apk`, `solumia-X.Y.Z-wear.apk`, `solumia-X.Y.Z-linux-x86_64.AppImage`,
`solumia-X.Y.Z-windows-x64-setup.exe`, plus a signed `SHA256SUMS.txt`.

Security: same path as the Craft Apps (`craft_apps.download_verified`). Until the signing key of
the Solumia releases is pinned in `SOLUMIA_FINGERPRINTS`, downloads are blocked: a Solumia app is
never downloaded checked only against its own release.
"""

from __future__ import annotations

import os
import stat
import subprocess
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

from . import names
from .craft_apps import CraftError, Release, download_verified, fetch_repo_release
from .platform_setup import System, dir_apps, dir_downloads

# Primary key "Solumia Release Signing Key" (infra/scripts/setup_release_keys); CI signs with its subkey.
SOLUMIA_FINGERPRINTS: tuple[str, ...] = ("401962C4ED4FA05AE568116E68F5115E5B50B880",)


@dataclass(frozen=True)
class SolumiaApp:
    id: str
    dispositivo: str  # celular | relogio | pc
    modelo: str  # file name with {v}
    sistema: str | None = None  # for PC: on which system it can be installed here

    def arquivo(self, version: str) -> str:
        return self.modelo.format(v=version)


CATALOG: dict[str, SolumiaApp] = {
    a.id: a
    for a in (
        SolumiaApp("android", "celular", "solumia-{v}-android.apk"),
        SolumiaApp("wear", "relogio", "solumia-{v}-wear.apk"),
        SolumiaApp("linux", "pc", "solumia-{v}-linux-x86_64.AppImage", "linux"),
        SolumiaApp("windows", "pc", "solumia-{v}-windows-x64-setup.exe", "windows"),
    )
}


def url_releases() -> str:
    return f"https://github.com/{names.REPOSITORY}/releases"


def fetch(version: str = "ultima") -> Release:
    return fetch_repo_release(names.REPOSITORY, names.DISPLAY_NAME, version)


def _app(app_id: str) -> SolumiaApp:
    try:
        return CATALOG[app_id]
    except KeyError as e:
        raise CraftError(f"app fora do catálogo: {app_id!r}") from e


def installs_here(app: SolumiaApp, system: System) -> bool:
    return app.sistema == system.so and system.arquitetura == "x86_64"


def download(app_id: str, system: System, version: str = "ultima", install: bool = False,
           log: Callable[[str], None] = print,
           progresso: Callable[[int, int | None], None] | None = None) -> dict[str, str]:
    """Downloads the verified installer into the Downloads/Solumia folder; with `install`, installs it on this PC."""
    app = _app(app_id)
    if not SOLUMIA_FINGERPRINTS:
        raise CraftError("as releases do Solumia ainda não têm chave de assinatura fixada no configurador; "
                        "download bloqueado por segurança")
    if install and not installs_here(app, system):
        raise CraftError(f"o app {app_id} não é para este sistema ({system.so} {system.arquitetura})")
    log(f"Consultando releases em {url_releases()}")
    release = fetch(version)
    name = app.arquivo(release.versao)
    folder = dir_downloads(system)
    folder.mkdir(parents=True, exist_ok=True)
    path, total = download_verified(release, name, folder, SOLUMIA_FINGERPRINTS, log, progresso)
    log(f"Salvo em {path}")
    if install:
        path = _install(path, system, log)
    return {"versao": release.versao, "arquivo": name, "sha256": total, "caminho": str(path)}


def _install(file: Path, system: System, log: Callable[[str], None]) -> Path:
    if system.windows:
        log("Abrindo o instalador do Solumia")
        subprocess.run([str(file)], check=True)
        return file
    destination = dir_apps(system).parent / "app" / "Solumia.AppImage"
    destination.parent.mkdir(parents=True, exist_ok=True)
    tmp = destination.with_suffix(".novo")
    tmp.write_bytes(file.read_bytes())
    tmp.chmod(tmp.stat().st_mode | stat.S_IXUSR)
    os.replace(tmp, destination)
    shortcut = Path(os.environ.get("XDG_DATA_HOME", Path.home() / ".local" / "share")) / "applications"
    shortcut.mkdir(parents=True, exist_ok=True)
    (shortcut / f"{names.PREFIX}-app.desktop").write_text(
        "[Desktop Entry]\nType=Application\nName=Solumia\n"
        f"Exec=\"{destination}\"\nTerminal=false\nCategories=Office;\n"
    )
    log(f"Solumia instalado em {destination}")
    return destination
