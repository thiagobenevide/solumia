"""Generation of the installation secrets, done on the host: the plain password never leaves this machine.

The hash and TOTP format is the same as `plataforma/backend/src/backend/auth/security.py`
(scrypt N=2^14, r=8, p=1; TOTP SHA1/6 digits/30 s), so the gateway accepts them unchanged.
"""

from __future__ import annotations

import base64
import hashlib
import hmac
import secrets
import time
from urllib.parse import quote

from . import names

# Names of the secrets in the vault.
PASSWORD_HASH = "conta.senha_hash"  # noqa: S105 - vault entry name, not a secret
TOTP = "conta.totp"
JWT = "gateway.jwt"
CLIENT_KEY = "gateway.chave_cliente"
WATCH_KEY = "gateway.chave_relogio"  # scope relogio: only the watch routes
WORKER_KEY = "gateway.chave_worker"
COLLABORA_PASSWORD = "collabora.senha_admin"  # noqa: S105 - vault entry name, not a secret
WOPI = "gateway.wopi"
SSH_PRIVATE_KEY = "ssh.{no}.privada"  # ed25519 generated by the configurator, per node
TUNNEL_PRIVATE_KEY = "tunel.privada"

_N, _R, _P = 2**14, 8, 1


def _b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).rstrip(b"=").decode()


def check_password(senha: str) -> list[str]:
    problems = []
    if len(senha) < 12:
        problems.append("mínimo de 12 caracteres")
    if senha.lower() == senha or senha.upper() == senha:
        problems.append("misture maiúsculas e minúsculas")
    if not any(c.isdigit() for c in senha):
        problems.append("inclua ao menos um número")
    return problems


def hash_password(senha: str) -> str:
    salt = secrets.token_bytes(16)
    key = hashlib.scrypt(senha.encode(), salt=salt, n=_N, r=_R, p=_P, dklen=32)
    return f"scrypt${_N}${_R}${_P}${_b64(salt)}${_b64(key)}"


def totp_secret() -> str:
    return base64.b32encode(secrets.token_bytes(20)).decode()


def uri_totp(secret: str, usuario: str) -> str:
    issuer = names.DISPLAY_NAME
    return (
        f"otpauth://totp/{quote(issuer)}:{quote(usuario)}"
        f"?secret={secret}&issuer={quote(issuer)}&algorithm=SHA1&digits=6&period=30"
    )


def totp_code(secret: str, step: int) -> str:
    key = base64.b32decode(secret.upper() + "=" * (-len(secret) % 8))
    digest = hmac.new(key, step.to_bytes(8, "big"), hashlib.sha1).digest()
    d = digest[-1] & 0x0F
    number = int.from_bytes(digest[d : d + 4], "big") & 0x7FFFFFFF
    return f"{number % 1_000_000:06d}"


def check_totp(secret: str, code: str, now: float | None = None) -> bool:
    """Used to reconfirm destructive actions (reinstall the VPS, export the vault)."""
    if not secret or len(code) != 6 or not code.isdigit():
        return False
    current = int((time.time() if now is None else now) // 30)
    return any(hmac.compare_digest(totp_code(secret, p), code) for p in (current - 1, current, current + 1))


def token(prefix: str = "", tamanho: int = 32) -> str:
    return prefix + secrets.token_urlsafe(tamanho)


def generate_ssh_key() -> tuple[str, str]:
    """(private key as OpenSSH PEM, public key on one line)."""
    from cryptography.hazmat.primitives import serialization
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

    key = Ed25519PrivateKey.generate()
    private = key.private_bytes(
        serialization.Encoding.PEM, serialization.PrivateFormat.OpenSSH, serialization.NoEncryption()
    ).decode()
    public = key.public_key().public_bytes(
        serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH
    ).decode()
    return private, f"{public} {names.SSH_KEY_COMMENT}"


def public_key_of(private_pem: str) -> str:
    from cryptography.hazmat.primitives import serialization

    key = serialization.load_ssh_private_key(private_pem.encode(), password=None)
    public = key.public_key().public_bytes(
        serialization.Encoding.OpenSSH, serialization.PublicFormat.OpenSSH
    ).decode()
    return f"{public} {names.SSH_KEY_COMMENT}"
